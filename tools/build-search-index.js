#!/usr/bin/env node
/* Builds site/assets/js/search-index.js, the data behind the search box on the home page.

   Run it from the repository root after changing any page:

       node tools/build-search-index.js

   No dependencies. It reads site/index.html for the list of pages, takes one entry per
   <section id="..."> of every page (number, title, kicker and text), and adds the questions,
   correct answers and explanations of that topic from the page's QUIZ bank.
   The search itself runs in the browser (site/assets/js/search.js); nothing here runs on a server. */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const site = path.join(__dirname, "..", "site");
const read = (f) => fs.readFileSync(path.join(site, f), "utf8");

// Reuse the text cleaner of the browser code so both sides agree.
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext("var window=this.window;" + read("assets/js/search.js"), sandbox);
const clean = sandbox.window.StudySearch.clean;

/* The object literal after "const QUIZ =", found by bracket matching that skips strings and comments. */
function quizBank(js) {
  const start = js.indexOf("const QUIZ = {");
  if (start < 0) return {};
  let i = js.indexOf("{", start), depth = 0;
  const from = i;
  for (; i < js.length; i++) {
    const c = js[i];
    if (c === '"' || c === "'" || c === "`") {
      for (i++; i < js.length && js[i] !== c; i++) if (js[i] === "\\") i++;
    } else if (c === "/" && js[i + 1] === "/") {
      i = js.indexOf("\n", i);
      if (i < 0) break;
    } else if (c === "/" && js[i + 1] === "*") {
      i = js.indexOf("*/", i) + 1;
    } else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) break;
  }
  try {
    // Some banks call small formatting helpers (sub, sup, ...) defined elsewhere in the page script.
    // Any unknown name becomes a function that returns its arguments as text.
    const helpers = new Proxy({}, {
      has: () => true,
      get: (_, k) => (typeof k === "symbol" ? undefined : (...args) => args.join(" ")),
    });
    return vm.runInNewContext("with (helpers) { (" + js.slice(from, i + 1) + ") }", { helpers });
  } catch (e) {
    console.warn("  could not read the QUIZ bank (" + e.message + "); questions left out for this page");
    return {};
  }
}

const index = read("index.html");
const cards = [...index.matchAll(/<a class="lecture-card[^"]*" href="([^"]+\.html)"[\s\S]*?<span class="lc-num">([\s\S]*?)<\/span>[\s\S]*?<h2>([\s\S]*?)<\/h2>/g)];
if (!cards.length) throw new Error("no lecture cards found in site/index.html");

const entries = [];
for (const [, file, num, title] of cards) {
  const html = read(file);
  const jsFile = path.join("assets", "js", file.replace(/\.html$/, ".js"));
  const bank = fs.existsSync(path.join(site, jsFile)) ? quizBank(read(jsFile)) : {};
  const where = clean(num) + " · " + clean(title);
  let n = 0;
  for (const [, attrs, inner] of html.matchAll(/<section\b([^>]*)>([\s\S]*?)<\/section>/g)) {
    const id = (attrs.match(/\bid="([^"]+)"/) || [])[1];
    if (!id) continue;
    const pick = (re) => clean((inner.match(re) || [, ""])[1]);
    const head = (inner.match(/<header[\s\S]*?<\/header>/) || [""])[0];
    const quizKeys = [...inner.matchAll(/data-quiz="([^"]+)"/g)].map((m) => m[1]);
    const quiz = quizKeys.map((k) => (bank[k] || []).map((q) => {
      const right = (q.options || []).filter((o) => o[1]).map((o) => o[0] + ". " + (o[2] || "")).join(" ");
      return (q.q || "") + " " + right;
    }).join(" ")).join(" ");
    entries.push({
      url: file + "#" + id,
      where: where,
      num: pick(/class="topic-num">([\s\S]*?)<\/span>/),
      title: pick(/<h2[^>]*>([\s\S]*?)<\/h2>/) || clean((attrs.match(/data-short="([^"]*)"/) || [, id])[1]),
      sub: pick(/class="kicker">([\s\S]*?)<\/p>/),
      body: clean(inner.replace(head, " ") + " " + quiz),
    });
    n++;
  }
  console.log(file.padEnd(34) + n + " topics, " + Object.keys(bank).length + " quiz groups");
}

const out = "/* Generated by tools/build-search-index.js. Do not edit by hand; run the script again instead. */\n" +
  "window.STUDY_SEARCH_INDEX = [\n" + entries.map((e) => JSON.stringify(e)).join(",\n") + "\n];\n";
fs.writeFileSync(path.join(site, "assets", "js", "search-index.js"), out);
console.log(entries.length + " entries, " + Math.round(out.length / 1024) + " KB written to site/assets/js/search-index.js");
